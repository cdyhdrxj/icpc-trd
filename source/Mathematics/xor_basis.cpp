// Что возвращается: вектор базиса b (каждый элемент — независимый
//   по XOR вектор, у каждого свой старший бит).
// Размер базиса = ранг множества по XOR.
// ============================================================
// Для чего применяется:
//  - Максимальный XOR подмножества (maxXor).
//  - Проверка достижимости числа через XOR (canGet).
//  - K-й по величине XOR подмножества (kthXor).
//  - Проверка линейной независимости чисел над GF(2).
//  - Cycle space графа: какие XOR-суммы рёбер достижимы.
// ============================================================
vector<int> buildBasis(const vector<int>& a) {
    vector<int> b(B, 0);          // b[i] — вектор с старшим битом i (или 0)
    for (int x : a) {
        int cur = x;
        for (int i = B - 1; i >= 0; --i) {
            if (!(cur >> i & 1)) continue;   // бит i не установлен — идём дальше
            if (!b[i]) { b[i] = cur; cur = 0; break; }   // нового лидера нашли — добавляем
            cur ^= b[i];                     // гасим бит i через уже имеющийся вектор
        }
    }
    return b;
}

// Подаём: базис b, индекс k (0 <= k < 2^rank).
// Возвращает: k-е число в отсортированном множестве всех XOR.
// Работает при условии, что базис приведён к "диагональному" виду.
int kthXor(vector<int> b, long long k) {
    // приводим базис к виду, где у каждого b[i] старший бит ровно i
    for (int i = 0; i < B; ++i)
        for (int j = i - 1; j >= 0; --j)
            if (b[i] >> j & 1) b[i] ^= b[j];
    // собираем только ненулевые векторы
    vector<int> c;
    for (int i = 0; i < B; ++i)
        if (b[i]) c.push_back(b[i]);
    // строим ответ по битам k
    int res = 0;
    for (int i = 0; i < (int)c.size(); ++i)
        if (k >> i & 1) res ^= c[i];
    return res;
}

